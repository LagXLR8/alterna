    private static boolean canForestRockReplace(BlockState state) {
        if (state == null || state.isAir()) return true;
        if (state.is(Blocks.WATER) || state.is(Blocks.WATER_CAULDRON)) return true;
        if (isCarveReplaceable(state)) return true;
        net.minecraft.world.level.block.Block b = state.getBlock();
        if (b instanceof BushBlock || b instanceof CarpetBlock || b instanceof FlowerBlock || b instanceof DoublePlantBlock) return true;
        if (state.is(BlockTags.FLOWERS) || state.is(BlockTags.SMALL_FLOWERS) || state.is(BlockTags.REPLACEABLE)) return true;
        return !state.isSolid();
    }

    private static void placeForestRock(WorldGenLevel level, BlockPos originPos, RandomSource random) {
        int radius = 1 + random.nextInt(2);
        int height = 1 + random.nextInt(2);
        BlockState[] rockPalette = new BlockState[] {
            Blocks.MOSSY_COBBLESTONE.defaultBlockState(),
            Blocks.COBBLESTONE.defaultBlockState(),
            Blocks.MOSS_BLOCK.defaultBlockState(),
            Blocks.STONE.defaultBlockState(),
            Blocks.ANDESITE.defaultBlockState()
        };

        for (int dx = -radius; dx <= radius; dx++) {
            for (int dz = -radius; dz <= radius; dz++) {
                for (int dy = 0; dy <= height; dy++) {
                    double distSq = (dx * dx) + (dz * dz) + (dy * dy * 1.5);
                    if (distSq <= (radius * radius + random.nextDouble() * 0.8)) {
                        BlockPos rockPos = originPos.offset(dx, dy, dz);
                        BlockState existing = level.getBlockState(rockPos);
                        if (canForestRockReplace(existing)) {
                            BlockState rock = rockPalette[random.nextInt(rockPalette.length)];
                            level.setBlock(rockPos, rock, 2);

                            BlockPos abovePos = rockPos.above();
                            if (level.getBlockState(abovePos).isAir() && random.nextFloat() < 0.35f) {
                                if (random.nextBoolean()) {
                                    level.setBlock(abovePos, Blocks.MOSS_CARPET.defaultBlockState(), 2);
                                } else {
                                    level.setBlock(abovePos, Blocks.SHORT_GRASS.defaultBlockState(), 2);
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    private static void placeForestFlowers(WorldGenLevel level, BlockPos originPos, RandomSource random) {
        int radius = 1 + random.nextInt(2);
        for (int dx = -radius; dx <= radius; dx++) {
            for (int dz = -radius; dz <= radius; dz++) {
                if (dx * dx + dz * dz <= radius * radius + 1) {
                    BlockPos flowerPos = originPos.offset(dx, 0, dz);
                    BlockPos groundPos = flowerPos.below();
                    if (level.getBlockState(flowerPos).isAir() && level.getBlockState(groundPos).isSolid()) {
                        if (random.nextFloat() < 0.65f) {
                            BlockState flower = FOREST_FLOWERS[random.nextInt(FOREST_FLOWERS.length)];
                            level.setBlock(flowerPos, flower, 2);
                        }
                    }
                }
            }
        }
    }

    private static void applyLedgeDecoration(WorldGenLevel level, BlockPos blockPos, Segment seg, int x, int y, int z, RiftLedge.Variant variant, boolean isTopSurface, boolean isBottomSurface, boolean isOuterEdge, double edgeDistNorm, double sCenter, double halfLength, double sHalfLength, double localA, RiftGiantLedge gl, double localB, double effectiveHalfWidth) {
        long seedHash = (long) x * 3129871L ^ (long) y * 116391L ^ (long) z * 91811L ^ seg.roughnessSeed;
        RandomSource random = RandomSource.create(seedHash);

        // Check if this ledge has a sparse "Dead Moss" organic circular patch (~15-20% chance)
        long ledgeSeed = (long) (sCenter * 1000) ^ seg.roughnessSeed;
        boolean hasDeadMossPatch = (Math.abs(ledgeSeed) % 100) < 18;
        boolean isDeadMossPath = false;

        if (hasDeadMossPatch) {
            double patchCenterA = sCenter * halfLength;
            double patchRadius = 4.0;
            double distToPatch = Math.abs(localA - patchCenterA);
            double noiseJitter = smoothNoise3D(x, y, z, seg.roughnessSeed ^ 0xD3AD005L, 0.20) * 2.5;
            if (distToPatch <= (patchRadius + noiseJitter) && edgeDistNorm >= 0.35) {
                isDeadMossPath = true;
            }
        }

        // 1. Place the body/surface block at (x, y, z)
        if (isTopSurface) {
            if (gl != null && gl.variant == RiftLedge.Variant.HOLLOW && RiftGiantLedge.isHollowRim(gl, localA, localB, x, y, z, halfLength, effectiveHalfWidth)) {
                level.setBlock(blockPos, Blocks.MUD.defaultBlockState(), 2);
                BlockPos topPos = blockPos.above();
                if (level.getBlockState(topPos).isAir() && random.nextFloat() < 0.25f) {
                    int caneHeight = 1 + random.nextInt(4);
                    for (int h = 0; h < caneHeight; h++) {
                        BlockPos canePos = topPos.above(h);
                        if (level.getBlockState(canePos).isAir()) {
                            boolean isTop = (h == caneHeight - 1);
                            BlockState caneState = ModBlocks.PURPLE_SUGAR_CANE.get().defaultBlockState()
                                    .setValue(PurpleSugarCaneBlock.TOP, isTop);
                            level.setBlock(canePos, caneState, 2);
                        } else {
                            break;
                        }
                    }
                }
            } else if (isDeadMossPath) {
                level.setBlock(blockPos, Blocks.PALE_MOSS_BLOCK.defaultBlockState(), 2);
            } else if (variant == RiftLedge.Variant.MOSS_DAZE || variant == RiftLedge.Variant.HOLLOW) {
                level.setBlock(blockPos, ModBlocks.WILD_MOSS_BLOCK.get().defaultBlockState(), 2);
            } else if (variant == RiftLedge.Variant.ROOTSHROOM_FOREST) {
                // Guard: don't overwrite surface block if a Rootshroom tree/stump from an adjacent chunk
                // has already placed its stem base on top of this block (cross-chunk boundary case)
                boolean hasStemAbove = level.getBlockState(blockPos.above()).is(ModBlocks.ROOTSHROOM_STEM.get());
                if (!hasStemAbove) {
                    double podzolNoise = smoothNoise3D(x, y, z, seg.roughnessSeed ^ 0x90D201L, 0.18);
                    if (podzolNoise > 0.10) {
                        level.setBlock(blockPos, Blocks.PODZOL.defaultBlockState(), 2);
                    } else if (random.nextBoolean()) {
                        level.setBlock(blockPos, Blocks.GRASS_BLOCK.defaultBlockState(), 2);
                    } else {
                        level.setBlock(blockPos, Blocks.MOSS_BLOCK.defaultBlockState(), 2);
                    }
                }
            } else {
                if (random.nextBoolean()) {
                    level.setBlock(blockPos, ModBlocks.WILD_MOSS_BLOCK.get().defaultBlockState(), 2);
                } else {
                    level.setBlock(blockPos, Blocks.GRASS_BLOCK.defaultBlockState(), 2);
                }
            }
        } else {
            // Body or underside block
            if (isOuterEdge && random.nextFloat() < 0.30f) {
                level.setBlock(blockPos, isDeadMossPath ? Blocks.PALE_MOSS_BLOCK.defaultBlockState() : ModBlocks.WILD_MOSS_BLOCK.get().defaultBlockState(), 2);
            } else {
                level.setBlock(blockPos, pickWallRock(x, y, z, seg.roughnessSeed ^ 0x1E6D6E7L), 2);
            }
        }

        // 2. Top surface vegetation & carpet at (x, y + 1, z)
        if (isTopSurface) {
            BlockPos topPos = blockPos.above();
            BlockState existingAbove = level.getBlockState(topPos);
            if (existingAbove.isAir()) {
                if (random.nextFloat() < 0.02f) {
                    placeForestRock(level, topPos, random);
                }

                boolean placedCarpet = false;
                if (isOuterEdge) {
                    // Outer rim edge: Moss Carpet with ~50% gaps/bare spots
                    if (random.nextFloat() < 0.50f) {
                        placeMossCarpet(level, topPos, isDeadMossPath, random);
                        placedCarpet = true;
                    }
                }

                // If no carpet was placed (interior OR bare carpet spot), allow plants/grass/bushes to grow!
                if (!placedCarpet) {
                    switch (variant) {
                        case MOSS_DAZE, HOLLOW -> {
                            double dsCenterNorm = Math.abs(localA - sCenter * halfLength) / Math.max(1.0, sHalfLength);
                            boolean inBerryCluster = (edgeDistNorm >= 0.30 && edgeDistNorm <= 0.55) && (dsCenterNorm < 0.25);

                            if (inBerryCluster && variant != RiftLedge.Variant.HOLLOW && random.nextFloat() < 0.75f) {
                                boolean isWhiteCurrant = (((long) (sCenter * 100) ^ (long) y ^ seg.roughnessSeed) & 1L) == 0L;
                                int stage = random.nextInt(4);
                                if (isWhiteCurrant) {
                                    level.setBlock(topPos, ModBlocks.WHITE_CURRANT_BERRY_BUSH.get().defaultBlockState().setValue(SweetBerryBushBlock.AGE, stage), 2);
                                } else {
                                    level.setBlock(topPos, Blocks.SWEET_BERRY_BUSH.defaultBlockState().setValue(SweetBerryBushBlock.AGE, stage), 2);
                                }
                            } else {
                                float roll = random.nextFloat();
                                if (roll < 0.30f) {
                                    if (random.nextFloat() < 0.25f && level.getBlockState(topPos.above()).isAir()) {
                                        DoublePlantBlock.placeAt(level, Blocks.TALL_GRASS.defaultBlockState(), topPos, 2);
                                    } else {
                                        level.setBlock(topPos, Blocks.SHORT_GRASS.defaultBlockState(), 2);
                                    }
                                } else if (roll < 0.42f) {
                                    if (random.nextFloat() < 0.30f && level.getBlockState(topPos.above()).isAir()) {
                                        DoublePlantBlock.placeAt(level, ModBlocks.TALL_DAZE.get().defaultBlockState(), topPos, 2);
                                    } else {
                                        level.setBlock(topPos, ModBlocks.SHORT_DAZE.get().defaultBlockState(), 2);
                                    }
                                } else if (roll < 0.57f) {
                                    placeForestFlowers(level, topPos, random);
                                } else if (roll < 0.70f) {
                                    level.setBlock(topPos, ModBlocks.STAR_LILY.get().defaultBlockState()
                                            .setValue(StarLilyBlock.AMOUNT, 1 + random.nextInt(2))
                                            .setValue(FlowerBedBlock.FACING, Direction.Plane.HORIZONTAL.getRandomDirection(random)), 2);
                                } else if (roll < 0.88f) {
                                    placeMossCarpet(level, topPos, isDeadMossPath, random);
                                }
                            }
                        }
                        case CLOUDBERRY -> {
                            double dsCenterNorm = Math.abs(localA - sCenter * halfLength) / Math.max(1.0, sHalfLength);
                            boolean inBerryCluster = (edgeDistNorm >= 0.30 && edgeDistNorm <= 0.55) && (dsCenterNorm < 0.25);

                            if (inBerryCluster && random.nextFloat() < 0.75f) {
                                boolean isWhiteCurrant = (((long) (sCenter * 100) ^ (long) y ^ seg.roughnessSeed) & 1L) == 0L;
                                int stage = random.nextInt(4);
                                if (isWhiteCurrant) {
                                    level.setBlock(topPos, ModBlocks.WHITE_CURRANT_BERRY_BUSH.get().defaultBlockState().setValue(SweetBerryBushBlock.AGE, stage), 2);
                                } else {
                                    level.setBlock(topPos, Blocks.SWEET_BERRY_BUSH.defaultBlockState().setValue(SweetBerryBushBlock.AGE, stage), 2);
                                }
                            } else {
                                float roll = random.nextFloat();
                                if (roll < 0.30f) {
                                    if (random.nextFloat() < 0.25f && level.getBlockState(topPos.above()).isAir()) {
                                        DoublePlantBlock.placeAt(level, Blocks.TALL_GRASS.defaultBlockState(), topPos, 2);
                                    } else {
                                        level.setBlock(topPos, Blocks.SHORT_GRASS.defaultBlockState(), 2);
                                    }
                                } else if (roll < 0.44f) {
                                    if (random.nextFloat() < 0.30f && level.getBlockState(topPos.above()).isAir()) {
                                        DoublePlantBlock.placeAt(level, ModBlocks.TALL_DAZE.get().defaultBlockState(), topPos, 2);
                                    } else {
                                        level.setBlock(topPos, ModBlocks.SHORT_DAZE.get().defaultBlockState(), 2);
                                    }
                                } else if (roll < 0.59f) {
                                    placeForestFlowers(level, topPos, random);
                                } else if (roll < 0.72f) {
                                    level.setBlock(topPos, ModBlocks.STAR_LILY.get().defaultBlockState()
                                            .setValue(StarLilyBlock.AMOUNT, 1 + random.nextInt(2))
                                            .setValue(FlowerBedBlock.FACING, Direction.Plane.HORIZONTAL.getRandomDirection(random)), 2);
                                } else if (roll < 0.88f) {
                                    placeMossCarpet(level, topPos, isDeadMossPath, random);
                                }
                            }
                        }
                        case STARLILY -> {
                            if (random.nextFloat() < 0.18f) {
                                // Grass gap (~18%) among Starlily beds
                                if (random.nextFloat() < 0.25f && level.getBlockState(topPos.above()).isAir()) {
                                    DoublePlantBlock.placeAt(level, Blocks.TALL_GRASS.defaultBlockState(), topPos, 2);
                                } else {
                                    level.setBlock(topPos, Blocks.SHORT_GRASS.defaultBlockState(), 2);
                                }
                            } else if (random.nextFloat() < 0.15f) {
                                placeForestFlowers(level, topPos, random);
                            } else {
                                int amount = (edgeDistNorm > 0.75) ? (1 + random.nextInt(2)) : (edgeDistNorm > 0.45) ? (2 + random.nextInt(2)) : (3 + random.nextInt(2));
                                level.setBlock(topPos, ModBlocks.STAR_LILY.get().defaultBlockState()
                                        .setValue(StarLilyBlock.AMOUNT, amount)
                                        .setValue(FlowerBedBlock.FACING, Direction.Plane.HORIZONTAL.getRandomDirection(random)), 2);
                            }
                        }
                        case ROOTSHROOM_FOREST -> {
                            RootshroomForestFeature.placeDirect(level, random, topPos, edgeDistNorm, seg.roughnessSeed);
                        }
                    }
                }
            }
        }

        // 3. Underside hanging vegetation at (x, y - 1, z) & outer rim side vines

        if (isBottomSurface) {
            BlockState ceilingState = level.getBlockState(blockPos);
            boolean isSturdyCeiling = isSturdySolidRock(ceilingState, level, blockPos, Direction.DOWN);
            float hangRoll = random.nextFloat();

            switch (variant) {
                case MOSS_DAZE, HOLLOW -> {
                    if (isSturdyCeiling && hangRoll < 0.50f) {
                        int length = 1 + random.nextInt(5);
                        for (int i = 1; i <= length; i++) {
                            BlockPos hangPos = blockPos.below(i);
                            BlockState targetState = level.getBlockState(hangPos);
                            if (targetState.isAir() || isCarveReplaceable(targetState)) {
                                BlockState mossState = (isDeadMossPath ? Blocks.PALE_HANGING_MOSS : ModBlocks.WILD_HANGING_MOSS.get())
                                        .defaultBlockState().setValue(HangingMossBlock.TIP, (i == length));
                                level.setBlock(hangPos, mossState, 2);
                            } else break;
                        }
                    }

                    if (gl != null && variant == RiftLedge.Variant.HOLLOW) {
                        double wallB = gl.side * effectiveHalfWidth;
                        double distFromWall = gl.side * (wallB - localB);
                        double lengthNorm = Math.abs(localA - gl.sCenter * halfLength) / Math.max(1.0, gl.sHalfLength);
                        double circularProfile = Math.sqrt(Math.max(0.0, 1.0 - lengthNorm * lengthNorm));
                        double maxTopReach = gl.reachWidth * circularProfile;

                        if (distFromWall >= 5.0 && distFromWall <= maxTopReach - 3.5) {
                            long currentAInt = Math.round(localA);
                            long currentDistInt = Math.round(distFromWall);
                            long centerA = Math.round(gl.sCenter * halfLength);
                            long relA = Math.abs(currentAInt - centerA);

                            if (relA % 7L == 0L && (currentDistInt % 7L == 0L || currentDistInt == Math.round(maxTopReach - 4.0))) {
                                if (isSturdyCeiling) {
                                    BlockPos treeAnchor = blockPos.below();
                                    long treeHash = currentAInt * 3129871L ^ currentDistInt * 116391L ^ seg.roughnessSeed;
                                    if ((Math.abs(treeHash) % 100) < 55) {
                                        // Defer to post-carve to avoid cross-chunk truncation
                                        seg.kapokAnchors.add(treeAnchor);
                                    }
                                }
                            }
                        }
                    }
                }
                case CLOUDBERRY -> {
                    // Boosted Cloudberry Vines density!
                    float spawnChance = (edgeDistNorm >= 0.70) ? 0.30f : (edgeDistNorm >= 0.40) ? 0.52f : 0.75f;
                    int maxLen = (edgeDistNorm >= 0.70) ? (2 + random.nextInt(3)) : (edgeDistNorm >= 0.40) ? (4 + random.nextInt(4)) : (6 + random.nextInt(5));
                    if (isSturdyCeiling && hangRoll < spawnChance) {
                        for (int i = 1; i <= maxLen; i++) {
                            BlockPos hangPos = blockPos.below(i);
                            BlockState targetState = level.getBlockState(hangPos);
                            if (targetState.isAir() || isCarveReplaceable(targetState)) {
                                boolean hasBerries = random.nextBoolean();
                                level.setBlock(hangPos, (i == maxLen ? ModBlocks.CLOUDBERRY_VINES.get() : ModBlocks.CLOUDBERRY_VINES_PLANT.get()).defaultBlockState().setValue(CaveVines.BERRIES, hasBerries), 2);
                            } else break;
                        }
                    }
                }
                case STARLILY -> {
                    if (isSturdyCeiling && hangRoll < 0.60f) {
                        // Hanging Star Lily on underside of Starlily ledges
                        int length = 3 + random.nextInt(8);
                        for (int i = 1; i <= length; i++) {
                            BlockPos hangPos = blockPos.below(i);
                            BlockState targetState = level.getBlockState(hangPos);
                            if (targetState.isAir() || isCarveReplaceable(targetState)) {
                                boolean hasFlowers = random.nextBoolean();
                                boolean isTip = (i == length);
                                BlockState state = (isTip ? ModBlocks.HANGING_STAR_LILY.get() : ModBlocks.HANGING_STAR_LILY_PLANT.get())
                                        .defaultBlockState().setValue(CaveVines.BERRIES, hasFlowers);
                                level.setBlock(hangPos, state, 2);
                            } else {
                                break;
                            }
                        }
                    }
                }
            }
        }
    }

    /**
     * pulse and angular harmonics. Shared by the carve and by cliff-tree
     * anchoring so the two can't drift apart.
     */
    private static final class LayerShape {
        final int y;
        final double t;
        final double centerX;
        final double centerZ;
        final double halfLength;
        final double halfWidth;

        LayerShape(int y, double t, double centerX, double centerZ, double halfLength, double halfWidth) {
            this.y = y;
            this.t = t;
            this.centerX = centerX;
            this.centerZ = centerZ;
            this.halfLength = halfLength;
            this.halfWidth = halfWidth;
        }
    }

    private static LayerShape layerShape(Segment seg, int layer) {
        int y = seg.origin.getY() - layer;
        double t = seg.depth <= 1 ? 1.0 : (double) layer / (double) (seg.depth - 1);
        double tt = terraceStep(t, seg.terraceCount, TERRACE_RISER_FRACTION);

        double taper;
        if (seg.allowBelowBedrock && y <= -350) {
            int layer350 = seg.origin.getY() - (-350);
            double t350 = seg.depth <= 1 ? 1.0 : (double) layer350 / (double) (seg.depth - 1);
            double tt350 = terraceStep(t350, seg.terraceCount, TERRACE_RISER_FRACTION);
            double taperAt350 = 1.0 - seg.narrowFraction * tt350;

            double blendT = clamp((-350.0 - y) / 150.0, 0.0, 1.0);
            double smoothB = blendT * blendT * (3.0 - 2.0 * blendT);
            taper = lerp(taperAt350, 1.0, smoothB);
        } else {
            taper = 1.0 - seg.narrowFraction * tt;
        }
        double bulge = 1.0 + seg.bulgeAmplitude * Math.sin(tt * Math.PI * BULGE_FREQUENCY + seg.bulgePhase);
        double profile = taper * bulge;

        RandomSource layerRandom = RandomSource.create(mixLayerSeed(seg.origin, layer));
        double jitter = 0.97 + layerRandom.nextDouble() * (JITTER_MAX - 0.97);

        double halfLength = seg.halfLength * profile * jitter;
        double halfWidth = seg.halfWidth * profile * jitter;

        // Drawn after jitter, from the same layer random - order matters, it's
        // what keeps a given layer's shape stable across chunks.
        double wobbleX = (layerRandom.nextDouble() - 0.5) * 0.25;
        double wobbleZ = (layerRandom.nextDouble() - 0.5) * 0.25;
        double centerX = seg.origin.getX() + interpPath(seg.pathOffsetX, t) + wobbleX;
        double centerZ = seg.origin.getZ() + interpPath(seg.pathOffsetZ, t) + wobbleZ;

        return new LayerShape(y, t, centerX, centerZ, halfLength, halfWidth);
    }

    private static double interpPath(double[] keyframes, double t) {
        double pos = t * (keyframes.length - 1);
        int i0 = (int) Math.floor(pos);
        if (i0 < 0) {
            return keyframes[0];
        }
        if (i0 >= keyframes.length - 1) {
            return keyframes[keyframes.length - 1];
        }
        double frac = pos - i0;
        return keyframes[i0] * (1.0 - frac) + keyframes[i0 + 1] * frac;
    }

    private static double radiusMultiplier(Segment seg, double theta, double t, double sNorm) {
        // Fade harmonic amplitude toward the tips (|sNorm| -> 1). On a long,
        // thin ellipse, angle is heavily compressed there, so ANY angular
        // perturbation piles up into spikes at the two ends. A quartic
        // falloff keeps the middle of the crack untouched and only pulls
        // amplitude down once we're fairly close to an end.
        double s2 = sNorm * sNorm;
        double tipFade = 1.0 - TIP_FADE_STRENGTH * s2 * s2;

        double m = 1.0;
        for (int k = 0; k < HARMONIC_FREQUENCIES.length; k++) {
            double phase = seg.harmonicPhases[k] + seg.harmonicTwists[k] * t;
            m += tipFade * seg.harmonicAmplitudes[k] * Math.sin(HARMONIC_FREQUENCIES[k] * theta + phase);
        }
        return clamp(m, HARMONIC_MIN_MULTIPLIER, HARMONIC_MAX_MULTIPLIER);
    }

    private static double widthPulse(Segment seg, double sNorm, double t) {
        double m = 1.0;
        for (int k = 0; k < WIDTH_FREQUENCIES.length; k++) {
            double phase = seg.widthPulsePhases[k] + seg.widthPulseTwists[k] * t;
            m += seg.widthPulseAmplitudes[k] * Math.sin(WIDTH_FREQUENCIES[k] * sNorm * Math.PI + phase);
        }
        return clamp(m, WIDTH_PULSE_MIN_MULTIPLIER, WIDTH_PULSE_MAX_MULTIPLIER);
    }

    /**
     * Flat "treads" hold width steady; short "risers" between them narrow it - i.e.
     * steps.
     */
    private static double terraceStep(double t, double terraceCount, double riserFraction) {
        double bandPos = t * terraceCount;
        int band = (int) Math.floor(bandPos);
        double within = bandPos - band;
        double treadEnd = 1.0 - riserFraction;
        double bandStartT = band / terraceCount;
        if (within <= treadEnd) {
            return Math.min(bandStartT, 1.0);
        }
        double blend = (within - treadEnd) / riserFraction;
        blend = blend * blend * (3 - 2 * blend); // smoothstep
        double bandEndT = (band + 1) / terraceCount;
        return Math.min(bandStartT + (bandEndT - bandStartT) * blend, 1.0);
    }

    /**
     * Deterministic 3D value hash, mapped to [-1, 1]. Used only as the raw lattice
     * sample for smoothNoise3D().
     */
    private static double hashNoise(int x, int y, int z, long seed) {
        long h = seed;
        h = h * 0x9E3779B97F4A7C15L + x;
        h = h * 0xBF58476D1CE4E5B9L + y;
        h = h * 0x94D049BB133111EBL + z;
        h ^= (h >>> 31);
        h *= 0xFF51AFD7ED558CCDL;
        h ^= (h >>> 33);
        long bits = (h >>> 40) & 0xFFFFFFL;
        return (bits / (double) 0xFFFFFFL) * 2.0 - 1.0;
    }

    private static double smoothstep(double t) {
        return t * t * (3 - 2 * t);
    }

    private static double lerp(double a, double b, double t) {
        return a + (b - a) * t;
    }

    /**
     * Coherent value noise - unlike hashNoise() (a different random value at
     * every single integer coordinate), this interpolates between hash values
     * sampled on a lattice spaced `scale` blocks apart, so nearby blocks get
     * similar values. That's what makes roughness/crumble read as "rock
     * breaking into chunks" instead of "random single-block noise scattered
     * everywhere" (the "bomb crater" look).
     */
    static double smoothNoise3D(double x, double y, double z, long seed, double scale) {
        double gx = x / scale, gy = y / scale, gz = z / scale;
        int x0 = (int) Math.floor(gx), y0 = (int) Math.floor(gy), z0 = (int) Math.floor(gz);
        double sx = smoothstep(gx - x0), sy = smoothstep(gy - y0), sz = smoothstep(gz - z0);

        double c000 = hashNoise(x0, y0, z0, seed);
        double c100 = hashNoise(x0 + 1, y0, z0, seed);
        double c010 = hashNoise(x0, y0 + 1, z0, seed);
        double c110 = hashNoise(x0 + 1, y0 + 1, z0, seed);
        double c001 = hashNoise(x0, y0, z0 + 1, seed);
        double c101 = hashNoise(x0 + 1, y0, z0 + 1, seed);
        double c011 = hashNoise(x0, y0 + 1, z0 + 1, seed);
        double c111 = hashNoise(x0 + 1, y0 + 1, z0 + 1, seed);

        double x00 = lerp(c000, c100, sx);
        double x10 = lerp(c010, c110, sx);
        double x01 = lerp(c001, c101, sx);
        double x11 = lerp(c011, c111, sx);

        return lerp(lerp(x00, x10, sy), lerp(x01, x11, sy), sz);
    }

    /**
     * True if water (river/ocean) is at or one block above this position, or in any
     * of the 4 horizontal neighbors.
     */
    private static boolean isWaterNearby(WorldGenLevel level, int x, int y, int z) {
        MutableBlockPos mpos = new MutableBlockPos();
        int[][] offsets = { { 0, 0 }, { 1, 0 }, { -1, 0 }, { 0, 1 }, { 0, -1 } };
        for (int[] off : offsets) {
            for (int dy = 0; dy <= 1; dy++) {
                mpos.set(x + off[0], y + dy, z + off[1]);
                if (level.getFluidState(mpos).is(FluidTags.WATER)) {
                    return true;
                }
            }
        }
        return false;
    }

    /**
     * Picks a boulder variant from coherent noise, so patches of the rim read as
     * one rock type at a time.
     */
    private static BlockState pickBoulderBlock(double n) {
        if (n > 0.5)
            return Blocks.MOSSY_COBBLESTONE.defaultBlockState();
        if (n > 0.0)
            return Blocks.COBBLESTONE.defaultBlockState();
        if (n > -0.5)
            return Blocks.ANDESITE.defaultBlockState();
        return Blocks.STONE.defaultBlockState();
    }

    /**
     * Places a sparse, height-faded boulder at (x, y, z) to block water from
     * draining into the rift. edgeT is 0 right at the carved boundary and 1
     * at the outer edge of the water-check band - both gap chance and
     * height are scaled by (1 - edgeT), so the rim is densest/tallest right
     * at the boundary and thins out into the surrounding terrain rather than
     * stopping in a hard line. A coarser noise (BOULDER_GAP_SCALE) than the
     * per-block variant noise decides gaps, so openings form as small
     * connected patches - deliberate channels for water to trickle through -
     * instead of single missing blocks. With BOULDER_GAP_CHANCE at 0, this
     * gap check is always skipped and the rim is fully sealed.
     */
    private static void placeBoulderRim(WorldGenLevel level, int x, int y, int z, long roughnessSeed, double edgeT) {
        double fade = 1.0 - edgeT;

        if (BOULDER_GAP_CHANCE > 0.0) {
            double gapRoll = (smoothNoise3D(x, y, z, roughnessSeed ^ 0x1234ABCDEF56L, BOULDER_GAP_SCALE) + 1.0) * 0.5;
            if (gapRoll < BOULDER_GAP_CHANCE * fade) {
                return; // leave a gap here for water to trickle through
            }
        }

        double heightNoise = (smoothNoise3D(x, y, z, roughnessSeed ^ 0x9E3779B97F4A7C15L, BOULDER_NOISE_SCALE) + 1.0)
                * 0.5;
        int height = 1 + (int) Math.round(heightNoise * (BOULDER_RIM_MAX_HEIGHT - 1) * fade);

        MutableBlockPos mpos = new MutableBlockPos();
        for (int dy = 0; dy < height; dy++) {
            // Never place boulder blocks at or below BEDROCK_BOUNDARY_Y - that
            // zone is part of the below-void space (water column, lava fill,
            // etc.) and a boulder here would block the rift's own water/fluid
            // rather than blocking surface water from draining in.
            if (y + dy <= BEDROCK_BOUNDARY_Y)
                break;
            mpos.set(x, y + dy, z);
            BlockState existing = level.getBlockState(mpos);
            if (existing.isAir() || !existing.getFluidState().isEmpty()) {
                double n = smoothNoise3D(x, y + dy, z, roughnessSeed ^ 0x9E3779B97F4A7C15L, BOULDER_NOISE_SCALE);
                level.setBlock(mpos, pickBoulderBlock(n), 2);
            }
        }
    }


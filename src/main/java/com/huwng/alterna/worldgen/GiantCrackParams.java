/**
 * Full parameters for one giant crack ("rift"), plus the carving logic
 * itself. See the class-level doc further down for why this is a pure
 * function of (seed, cellX, cellZ) instead of a StructurePiece.
 *
 * RIFT SHAPING (on top of the original ellipse-with-harmonics silhouette):
 * - WIDTH PULSE: half-width is modulated by a sine sum evaluated along the
 * crack's own length axis (not angle), so it bulges into chambers and
 * pinches into narrows as it runs - the thing that actually reads as
 * "rift" instead of "stretched ellipse".
 * - WALL ROUGHNESS: two octaves of *coherent* value noise (interpolated
 * across a lattice several blocks apart, not a fresh random value per
 * voxel) perturb the carve boundary, so walls break into jagged rock
 * faces instead of either a smooth curve or single-block "sandpaper"
 * noise.
 * - EDGE CRUMBLE: just outside the clean boundary (above the void
 * boundary only - the sandstone/bedrock safety wall stays clean),
 * blocks have a fading chance of breaking away too, using the same
 * coherent noise so missing rock comes off in patches/clumps instead of
 * scattered single blocks.
 * - TERRACE STEPS: depth is quantized into bands - flat "treads" hold
 * width steady, short "risers" between them do the actual narrowing,
 * producing visible ledges down the walls.
 * - BRANCHES: 1-3 smaller Segments spawn from points along the main
 * centerline, angled off from it, tapering to a point - literal side
 * offshoots, generated by reusing the same Segment machinery.
 * - TIP FADE: the angular-harmonic perturbation's amplitude is faded
 * down to near-zero as we approach either end of the crack (|sNorm| ->
 * 1). On a highly elongated ellipse, angle is heavily compressed near
 * the two tips, so any angular perturbation - regardless of its
 * frequency - bunches up into spiky artifacts there. Fading amplitude
 * out at the tips keeps mid-length detail while smoothing the ends.
 * - BOULDER RIM: where the carve boundary (above-void only) is adjacent
 * to existing water, a sparse, height- and density-faded scatter of
 * boulder blocks is placed instead of crumbling/opening the wall, so
 * rivers/oceans don't drain straight into the rift. It intentionally
 * leaves noise-driven gaps (in clumps, not single voxels) so some
 * water can still trickle through, and fades out toward the outer
 * edge of the check band so it blends into the surrounding terrain
 * instead of stopping abruptly. Set BOULDER_GAP_CHANCE to 0 for a
 * fully sealed rim (see field doc below).
 * - LAVA RIM: identical mechanism to the boulder rim, checked separately
 * against FluidTags.LAVA, using heat-appropriate blocks (blackstone,
 * basalt, deepslate, tuff) instead of cobblestone/mossy cobblestone.
 * Set LAVA_RIM_GAP_CHANCE to 0 for a fully sealed rim.
 * - GOBLET TREES: giant trees that grow OUT OF the rift walls instead of
 * standing on a floor, in the deep below-bedrock stretch of the rift.
 * This file only decides WHERE they hang from - see buildGobletTrees()
 * and the GOBLET TREE ANCHORING constants. Their shape and block
 * placement live in GobletTree; the scheduling that guarantees carving
 * finishes first lives in GobletTreeFeature, which is registered at a
 * later decoration step than GiantCrackFeature.
 * - ROOT CONNECTORS: thin runs of wood that trace the wall's own contour
 * to link neighbouring goblet trees on the same wall into one visible
 * root network, instead of leaving each tree an isolated stem. This
 * file only decides WHICH trees get linked and WHERE the link runs -
 * see buildRootConnectors() and the ROOT CONNECTORS constants. The
 * actual block placement lives in RootConnector.
 * - SANDSTONE BLEND: the rough, crumbly above-bedrock wall texture fades
 * into the smooth sandstone buffer over SANDSTONE_TRANSITION_HEIGHT
 * blocks just above BEDROCK_BOUNDARY_Y, instead of switching in one
 * hard step. Wall roughness/crumble amplitude ramp down and coherent-
 * noise sandstone patches ramp up across that band, so the texture
 * reads as a gradual weathering-into-buffer instead of a seam.
 * - BOTTOM FILL: the very bottom of the main crack (only the main
 * segment ever reaches this deep - see allowBelowBedrock) is no longer
 * left as open void. From the floor up it is filled with a fixed
 * stack: a 3-block bedrock floor, then a band of obsidian, then a
 * band of lava, then a thin band of magma block, then a second thin
 * obsidian cap, and above that a column of water reaching all the way
 * up to BOTTOM_FILL_WATER_TOP_Y. Only the thicknesses of the
 * obsidian/lava/magma bands are randomized per-crack (within fixed
 * ranges); the bedrock floor and the top water boundary are fixed.
 * See buildSegment() for how the band boundaries are computed and
 * bottomFillBlock() for how a given Y is mapped to a block. This only
 * ever overrides what would otherwise be carved to AIR inside the
 * core cross-section (coreDist <= mSq) - it does not touch the
 * sandstone buffer or the bedrock safety wall on the sides.
 *
 * SANDSTONE/BEDROCK CONTAINMENT FIX: the below-bedrock sandstone buffer
 * and bedrock safety wall must be sized from effectiveHalfWidth (the
 * width AFTER widthPulse is applied), not the segment's base halfWidth.
 * widthPulse can widen the crack up to 1.5x at bulge points along its
 * length; sizing containment off the unpulsed width left the buffer too
 * thin exactly at those bulges, letting the void carve punch straight
 * through sandstone and bedrock. Containment width is now recomputed
 * per-block inside carveLayer() rather than once per layer.
 *
 * WHY THIS EXISTS INSTEAD OF A StructurePiece:
 * Vanilla's structure-reference system only searches an ~8-chunk (128
 * block) radius around a chunk for structure starts to attach to, so any
 * crack bigger than that silently loses terrain at its far ends. Instead
 * of fighting that limit, this class makes every crack a pure, stateless
 * function of (world seed, cell X, cell Z) - see forCell(). Given the same
 * three inputs it always reconstructs the exact same crack, so ANY chunk,
 * whether it's the crack's origin chunk or one 15 chunks away, can
 * independently ask "does the crack from cell (cx, cz) reach into me?"
 * and carve its own portion - with no dependency on chunk generation
 * order and no persisted state (SavedData/NBT) required at all.
 *
 * GiantCrackFeature (registered as a normal Feature, so it runs
 * unconditionally on every chunk) is what calls forCell() for the current
 * chunk's cell and its 8 neighbors, then calls carveChunk() on any crack
 * whose reach might overlap the current chunk.
 *
 * NOTE ON FLOATING FEATURES (e.g. amethyst geodes) SURVIVING INSIDE THE
 * CARVED VOID: this class only ever removes/replaces blocks that exist at
 * the moment carveChunk() runs. If GiantCrackFeature is registered at a
 * decoration step that runs BEFORE features like geodes (vanilla geodes
 * generate in the UNDERGROUND_DECORATION step), then the geode gets
 * placed into the world AFTER the crack has already carved that space,
 * with no awareness that it's now inside a void - so part or all of it
 * can end up floating. This carving code cannot fix that by itself: the
 * actual fix is registering GiantCrackFeature at a LATER decoration step
 * than every feature you don't want floating (e.g. VEGETAL_DECORATION or
 * TOP_LAYER_MODIFICATION), so the crack always carves last and cleans up
 * anything placed earlier. That registration lives wherever
 * GiantCrackFeature is added to the biome's GenerationStep.Decoration
 * list, not in this file.
 *
 * Above the vanilla bedrock layer the walls are left as whatever terrain
 * was already there (normal stone/deepslate), same as vanilla caves. At
 * and below BEDROCK_BOUNDARY_Y it keeps carving straight through bedrock.
 * From there out to BEDROCK_WALL_OFFSET blocks past the crack, terrain is
 * replaced with smooth sandstone (an obviously "artificial" buffer), and
 * beyond that a thin bedrock wall forms the hard limit - see
 * VoidFallHandler for why the below-bedrock zone needs a hard limit.
 */
